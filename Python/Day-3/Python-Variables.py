""" 
Variables in python are used to store data. 
They can hold different types of data, such as numbers, strings, lists, etc.
 """

a = 10 # integer variable
b = 3.14 # float variable
c = "Hello, World!" # string variable
print(a) # Output: 10
print(b) # Output: 3.14
print(c) # Output: Hello, World!

list = [8,2.3, [-4, 5], ["Apple", "Banana"]] # list variable
print(list) # Output: [8, 2.3, [-4, 5], ['Apple', 'Banana']]

tuple = (1, 2, 3) # tuple variable
print(tuple) # Output: (1, 2, 3)

# Mapped Data Types: dict, set
dict = {"name": "Alice", "age": 30} # dictionary variable
print(dict) # Output: {'name': 'Alice', 'age': 30}
set = {1, 2, 3} # set variable
print(set) # Output: {1, 2, 3}