# The print() function in Python can take multiple arguments and has two optional parameters: end and sep.
# The end parameter specifies what to print at the end of the output. By default, it is a newline character (\n), which means that each print statement will be on a new line.
# The sep parameter specifies what to print between the arguments. By default, it is a space character, which means that the arguments will be separated by a space.
print("1", "2", "3", end="***", sep="$$" );
print("4", "5", "6");
print("This will be in a new line as previous print statement does not have end parameter");
