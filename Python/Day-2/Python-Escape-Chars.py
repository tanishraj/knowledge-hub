# \n is used to create a new line in the output.
print("This is first line.\nThis is second line.");

# \t is used to create a tab space in the output.
print("This is a tab character:\tSee the space after the colon.");

# \\ is used to print a backslash character.
print("This is a backslash character: \\");

# \' is used to print a single quote character.
print("This is a single quote character: \'");

# \" is used to print a double quote character.
print("This is a double quote character: \"");